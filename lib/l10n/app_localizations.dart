import 'package:flutter/foundation.dart';
import 'package:flutter/material.dart';

class AppLocalizations {
  const AppLocalizations(this.locale);

  final Locale locale;

  static const supportedLocales = <Locale>[
    Locale('en'),
    Locale.fromSubtags(languageCode: 'zh', scriptCode: 'Hans'),
    Locale.fromSubtags(languageCode: 'zh', scriptCode: 'Hant'),
    Locale('es'),
    Locale('ja'),
    Locale('fr'),
    Locale('ko'),
    Locale('ru'),
  ];

  static const LocalizationsDelegate<AppLocalizations> delegate =
      _AppLocalizationsDelegate();

  static AppLocalizations of(BuildContext context) =>
      Localizations.of<AppLocalizations>(context, AppLocalizations)!;

  static Locale resolve(List<Locale>? preferred) {
    for (final locale in preferred ?? const <Locale>[]) {
      if (locale.languageCode == 'en') return const Locale('en');
      if (locale.languageCode == 'zh') {
        final traditional =
            locale.scriptCode == 'Hant' ||
            const {
              'TW',
              'HK',
              'MO',
            }.contains(locale.countryCode?.toUpperCase());
        return Locale.fromSubtags(
          languageCode: 'zh',
          scriptCode: traditional ? 'Hant' : 'Hans',
        );
      }
      if (const {'es', 'ja', 'fr', 'ko', 'ru'}.contains(locale.languageCode)) {
        return Locale(locale.languageCode);
      }
    }
    return const Locale('en');
  }

  String text(String key, [Map<String, Object> values = const {}]) {
    final language = switch (locale.languageCode) {
      'zh' => locale.scriptCode == 'Hant' ? 'zhHant' : 'zhHans',
      'es' || 'ja' || 'fr' || 'ko' || 'ru' => locale.languageCode,
      _ => 'en',
    };
    var value =
        (_translations[language] ?? _translations['en']!)[key] ??
        _translations['en']![key] ??
        key;
    for (final entry in values.entries) {
      value = value.replaceAll('{${entry.key}}', '${entry.value}');
    }
    return value;
  }

  @visibleForTesting
  static bool get translationsComplete {
    final expected = _translations['en']!.keys.toSet();
    return _translations.values.every(
      (translation) => setEquals(translation.keys.toSet(), expected),
    );
  }
}

extension AppLocalizationContext on BuildContext {
  AppLocalizations get l10n => AppLocalizations.of(this);
}

class _AppLocalizationsDelegate
    extends LocalizationsDelegate<AppLocalizations> {
  const _AppLocalizationsDelegate();

  @override
  bool isSupported(Locale locale) => const {
    'en',
    'zh',
    'es',
    'ja',
    'fr',
    'ko',
    'ru',
  }.contains(locale.languageCode);

  @override
  Future<AppLocalizations> load(Locale locale) =>
      SynchronousFuture(AppLocalizations(locale));

  @override
  bool shouldReload(_AppLocalizationsDelegate old) => false;
}

